import ro.atlasistoric.data.*
import ro.atlasistoric.ocr.suggestOcrLinks
import ro.atlasistoric.util.*

fun main() {
    check(TimeMath.century(1) == 1)
    check(TimeMath.century(100) == 1)
    check(TimeMath.century(101) == 2)
    check(TimeMath.century(-1) == -1)
    check(TimeMath.century(-100) == -1)
    check(TimeMath.century(-101) == -2)
    check(TimeMath.centuryBounds(-1) == -100..-1)
    check(TimeMath.centuryBounds(13) == 1201..1300)
    check(TimeMath.overlaps(1250, 1270, 1201, 1300))
    check(!TimeMath.overlaps(1250, 1270, 1301, 1400))
    check(!TimeMath.overlaps(null, null, 1201, 1300))
    check(TimeMath.relationActive(null, null, 1201, 1300))
    val geos = listOf(
        EntityRelation("transilvania", "regatul", "PART_OF", 1300, 1400),
        EntityRelation("cluj", "transilvania", "PART_OF", 1200, 1500)
    )
    check(descendantsOfPlace("regatul", geos, 1350, 1350) == setOf("regatul", "transilvania", "cluj"))
    check(descendantsOfPlace("regatul", geos, 1500, 1600) == setOf("regatul"))
    val topics = listOf(HistoricalTopic("p", "Politic"), HistoricalTopic("d", "Diplomație", "p"))
    check(descendantsOfTopic("p", topics) == setOf("p", "d"))
    val candidate = suggestOcrLinks("În 1280 apare Transilvania în cronică.",
        listOf(HistoricalEntity("t", "Transilvania", "PLACE")), topics)
    check(candidate.entityIds == setOf("t"))
    check(candidate.candidateYears == listOf(1280))
    check(TemporalNavigation.advanceYear(-1, 1) == 1)
    check(TemporalNavigation.advanceYear(1, -1) == -1)
    check(TemporalNavigation.advanceYear(-44, 3) == -41)
    check(TemporalNavigation.advanceCentury(-1, 1) == 1)
    check(TemporalNavigation.advanceCentury(1, -1) == -1)
    check(TemporalNavigation.visible("SECOL", 1200, 1).size == 15)
    check(TemporalNavigation.visible("AN", 1, 1).none { it.from == 0 })
    check(TemporalNavigation.visible("LUNA", 1900, 1).size == 12)
    check(TemporalNavigation.visible("ZI", 1900, 2).size == 31)
    check(TemporalNavigation.fromKey("C:-1")?.from == -100)
    check(TemporalNavigation.fromKey("Y:0") == null)
    check(TemporalNavigation.fromKey("M:1900:13") == null)
    check(TemporalNavigation.fromKey("D:1900:2:32") == null)
    check(TemporalNavigation.fromKey("E:Început: târziu")?.era == "Început: târziu")
    val newEra = TemporalNavigation.visible("EPOCA", 1900, 1, listOf("modern", "modern", "antic"))
    check(newEra.map { it.label } == listOf("antic", "modern"))
    check(TemporalNavigation.fromKey("Y:1280")!!.matches(1280, 1280, null, null, ""))
    check(!TemporalNavigation.fromKey("Y:1280")!!.matches(null, null, null, null, ""))
    val ancient = suggestOcrLinks("În 44 î.Hr. și 27 î.Hr. iar în 106 d.Hr.", emptyList(), emptyList())
    check(ancient.candidateYears == listOf(-44, -27, 106))
    check(suggestOcrLinks("anul -7 la Roma", emptyList(), emptyList()).candidateYears == listOf(-7))
    check(TimeMath.normalize("  Ştefan   cel MARE  ") == TimeMath.normalize("Stefan cel mare"))
    check(TimeMath.normalize("Țara Românească") == "tara romaneasca")
    println("VALIDARE LOGICĂ: toate cele 35 de scenarii trecute")
}
